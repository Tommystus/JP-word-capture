  /* ---------- kana normalisation ---------- */

  function katakanaToHiragana(s) {
    var out = '';
    for (var i = 0; i < s.length; i++) {
      var c = s.charCodeAt(i);
      if (c >= 0x30A1 && c <= 0x30F6) {          // ァ..ヶ
        out += String.fromCharCode(c - 0x60);
      } else if (s[i] === 'ヶ' || s[i] === 'ヵ') {
        out += 'か';
      } else {
        out += s[i];
      }
    }
    return out;
  }

  var KANJI_RE = /[一-鿿々〆ヶ]/;

  /* ---------- kanji -> hiragana ---------- */

  var WORD_KEYS = Object.keys(WORDS)
    .filter(function (k) { return KANJI_RE.test(k) && WORDS[k]; })
    .sort(function (a, b) { return b.length - a.length; });
  var MAX_WORD_LEN = WORD_KEYS.reduce(function (m, k) { return Math.max(m, k.length); }, 1);

  function toHiragana(text) {
    var out = '';
    var i = 0;
    while (i < text.length) {
      var ch = text[i];
      if (KANJI_RE.test(ch)) {
        var matched = false;
        var max = Math.min(MAX_WORD_LEN, text.length - i);
        for (var L = max; L >= 2 && !matched; L--) {
          var sub = text.substr(i, L);
          if (WORDS[sub]) { out += WORDS[sub]; i += L; matched = true; }
        }
        if (!matched && SINGLE[ch]) { out += SINGLE[ch]; i++; continue; }
        if (!matched) { out += ch; i++; continue; }   // unknown: keep kanji
        continue;
      }
      out += ch;
      i++;
    }
    return katakanaToHiragana(out);
  }

