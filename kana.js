  var VOWELS = 'aeiou';

  function toRomaji(kana) {
    var hira = katakanaToHiragana(kana);
    var out = '';
    var i = 0;

    while (i < hira.length) {
      var two = hira.substr(i, 2);

      // digraph
      if (COMBO[two]) { out += COMBO[two]; i += 2; continue; }

      var c = hira[i];

      // sokuon: double the next consonant
      if (c === 'っ') {
        i++;
        var nextR = hira.substr(i, 2);
        var nx = COMBO[nextR] || BASE[hira[i]] || '';
        if (nx) out += nx.charAt(0);
        continue;
      }

      // chōonpu (ー) lengthens the preceding vowel; it replaces it rather than
      // adding another, so こーひー -> "kohii", not "koohii"
      if (c === 'ー') {
        if (out && VOWELS.indexOf(out.charAt(out.length - 1)) >= 0) {
          out = out.slice(0, -1) + out.charAt(out.length - 1);
        }
        i++;
        continue;
      }

      // ん: n, or m before b/p/m, or n' before a vowel / y-row
      if (c === 'ん') {
        var nx2 = hira.substr(i + 1, 2);
        var nx1 = hira[i + 1];
        var after = COMBO[nx2] || BASE[nx1] || '';
        var a0 = after.charAt(0);
        if (!a0) out += 'n';                       // end of string
        else if (a0 === 'b' || a0 === 'p' || a0 === 'm') out += 'm';
        else if (VOWELS.indexOf(a0) >= 0 || a0 === 'y') out += "n'";
        else out += 'n';
        i++;
        continue;
      }

      var r = BASE[c];
      if (r !== undefined) out += r;
      // unknown chars (kanji, latin, etc.) are skipped
      i++;
    }

    return out.trim();
  }

  global.Kana = {
    toHiragana: toHiragana,
    toRomaji: toRomaji
  };
